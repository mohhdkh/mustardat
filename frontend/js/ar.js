    function fixMojibake(value) {
        let result = value;
        Object.entries(mojibake).forEach(([broken, correct]) => {
            result = result.split(broken).join(correct);
        });
        return result;
    }

    function translate(value) {
        if (typeof value !== 'string' || !value.trim()) return value;
        let result = fixMojibake(value);
        const trimmed = result.trim();
        if (exact[trimmed]) {
            return result.replace(trimmed, exact[trimmed]);
        }
        // Translate an exact label even when an icon appears before it (e.g. "📱 Phone").
        const prefixed = trimmed.match(/^([^\p{L}\p{N}]*)([\p{L}\p{N}][\s\S]*)$/u);
        const prefixedTranslation = prefixed && (exact[prefixed[2]] || exact[prefixed[2].toLowerCase()]);
        if (prefixedTranslation) {
            return result.replace(trimmed, `${prefixed[1]}${prefixedTranslation}`);
        }
        phraseReplacements.forEach(([pattern, replacement]) => {
            result = result.replace(pattern, replacement);
        });
        return result;
    }

    function translateElement(element) {
        if (!(element instanceof Element)) return;
        ['placeholder', 'title', 'alt'].forEach(attribute => {
            if (element.hasAttribute(attribute)) {
                const oldValue = element.getAttribute(attribute);
                const newValue = translate(oldValue);
                if (newValue !== oldValue) element.setAttribute(attribute, newValue);
            }
        });
    }

    function translateTree(root) {
        if (!root) return;
        if (root.nodeType === Node.TEXT_NODE) {
            const parentTag = root.parentElement?.tagName;
            if (!['SCRIPT', 'STYLE', 'CODE'].includes(parentTag)) {
                const translated = translate(root.nodeValue);
                if (translated !== root.nodeValue) root.nodeValue = translated;
            }
            return;
        }
        if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;
        if (root.nodeType === Node.ELEMENT_NODE) translateElement(root);
        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
        let node;
        while ((node = walker.nextNode())) {
            if (node.nodeType === Node.TEXT_NODE) {
                const parentTag = node.parentElement?.tagName;
                if (!['SCRIPT', 'STYLE', 'CODE'].includes(parentTag)) {
                    const translated = translate(node.nodeValue);
                    if (translated !== node.nodeValue) node.nodeValue = translated;
                }
            } else {
                translateElement(node);
            }
        }
    }

